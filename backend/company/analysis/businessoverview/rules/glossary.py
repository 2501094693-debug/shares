"""术语白话替换表：把财报术语换成普通人能懂的说法。

纯正则替换，可预期、可审计。替换只在渲染层执行，不影响任何计算数字。
"""

from __future__ import annotations

import re

# (正则, 白话)
GLOSSARY: tuple[tuple[str, str], ...] = (
    (r"归母净利润", "净利润里属于股东的部分"),
    (r"扣非(后)?净利润|扣非归母", "扣掉买卖资产等一次性收益之后的利润"),
    (r"经营活动?产生的现金流(量净额)?", "公司实际收到的现金"),
    (r"应收账款?", "客户欠公司的钱"),
    (r"存货", "仓库里还没卖掉的货"),
    (r"固定资产", "厂房设备"),
    (r"商誉", "收购时多付的钱"),
    (r"毛利率", "每 100 元收入里留下多少毛利"),
    (r"净利率", "每 100 元收入最终留下多少净利"),
    (r"净资产收益率|ROE", "股东每投入 100 元一年赚多少"),
    (r"总资产收益率|ROA", "公司每 100 元资产一年赚多少"),
    (r"资产负债率", "借的钱占总资产的比例"),
    (r"营业收入|营收", "公司卖东西收到的钱"),
    (r"营业成本", "卖这些货的直接成本"),
    (r"同比", "和去年同期比"),
    (r"环比", "和上个季度比"),
    (r"市占率", "在同行里占多少份额"),
    (r"产能利用率", "生产线开了多少"),
    (r"在建工程", "还没完工的厂房项目"),
    (r"投资收益", "靠投资赚到的钱"),
    (r"政府补助", "政府给的钱"),
    (r"非经常性损益", "跟主营无关的一次性收益"),
)

_COMPILED: tuple[tuple[re.Pattern[str], str], ...] = tuple(
    (re.compile(pattern), repl) for pattern, repl in GLOSSARY
)


def gloss_text(text: str) -> str:
    """对一段文本做术语白话替换（保留原有措辞，只做括注式替换）。"""
    if not text:
        return ""
    out = text
    for pattern, repl in _COMPILED:
        out = pattern.sub(repl, out)
    return out